#!/usr/bin/env bash
# Rewrites the two generated sections of the phase's qa-report.md from the QA
# artifacts: "## Visual comparison" from qa/visual.tsv (written by
# visual-diff.mjs) and "## Accessibility" from qa/a11y/<screen>-<width>.json (axe
# results from capture.mjs or QA's own tests; one result or an array per file)
# plus qa/a11y-checklist.tsv (manual checks; failures are added up by impact).
# It's the only writer of those sections; signoff-check.sh reads them.
# Usage: qa-summary.sh [phase-dir]
source "$(dirname "${0//\\//}")/lib.sh"
require_jq
dir="${1:-$(phase_dir)}"
report="$dir/qa-report.md"
[[ -n "$dir" && -f "$report" ]] || { echo "qa-summary: no qa-report.md in ${dir:-the active phase}" >&2; exit 1; }

visual=""
if [[ -f "$dir/qa/visual.tsv" ]]; then
  visual=$(tr -d '\r' < "$dir/qa/visual.tsv" | awk -F'\t' 'NF >= 5 { printf "| %s | %s | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5, $6 }')
fi

a11y=""
for f in "$dir"/qa/a11y/*.json; do
  [[ -f "$f" ]] || continue
  base=$(basename "$f" .json)
  counts=$(tr -d '\r' < "$f" | jqr '[(if type == "array" then .[] else . end) | .violations[]? | .impact]
    | [(map(select(. == "critical")) | length), (map(select(. == "serious")) | length),
       (map(select(. == "moderate")) | length), (map(select(. == "minor")) | length)] | @tsv') \
    || { echo "qa-summary: can't read $f as axe results" >&2; exit 1; }
  IFS=$'\t' read -r c s m n <<<"$counts"
  a11y+="| ${base%-*} | ${base##*-} | $c | $s | $m | $n | qa/a11y/$base.json | axe |"$'\n'
done

# Manual checklist (qa/a11y-checklist.tsv): add up the failed checks per screen and
# width by impact; a pair with only passing checks gets a row of zeros. Result and
# impact are compared in lower case, a fail with an unknown impact counts as
# serious, and a row whose result isn't pass or fail (a header) is skipped.
if [[ -f "$dir/qa/a11y-checklist.tsv" ]]; then
  checklist=$(tr -d '\r' < "$dir/qa/a11y-checklist.tsv" | awk -F'\t' '
    /^[ \t]*#/ || NF < 5 { next }
    { res = tolower($4); imp = tolower($5)
      gsub(/^[ \t]+|[ \t]+$/, "", res); gsub(/^[ \t]+|[ \t]+$/, "", imp)
      if (res != "pass" && res != "fail") next   # a header row or an unfilled result
      k = $1 "\t" $2
      if (!(k in seen)) { seen[k] = 1; order[++n] = k; scr[k] = $1; wid[k] = $2 }
      if (res == "fail") {
        if (imp !~ /^(critical|serious|moderate|minor)$/) imp = "serious"   # unknown impact still blocks
        c[k, imp]++
      } }
    END { for (i = 1; i <= n; i++) { k = order[i]
      printf "| %s | %s | %d | %d | %d | %d | qa/a11y-checklist.tsv | checklist |\n", scr[k], wid[k],
        c[k, "critical"], c[k, "serious"], c[k, "moderate"], c[k, "minor"] } }')
  a11y+="$checklist${checklist:+$'\n'}"
fi

# Replace a "## <name>" section's body (up to the next "## " heading), or append
# the section if it's missing. Keeps the file's line endings.
replace_section() { # file name body-file
  local tmp crlf=""
  grep -q $'\r$' "$1" && crlf=1
  tmp=$(mktemp)
  tr -d '\r' < "$1" | awk -v name="## $2" -v bodyfile="$3" '
    function body() { while ((getline line < bodyfile) > 0) print line; close(bodyfile) }
    $0 == name { print; body(); skip = 1; found = 1; next }
    skip && /^## / { skip = 0 }
    !skip { print }
    END { if (!found) { print ""; print name; body() } }' > "$tmp"
  if [[ -n "$crlf" ]]; then sed 's/$/\r/' "$tmp" > "$1"; else cat "$tmp" > "$1"; fi
  rm -f "$tmp"
}

body=$(mktemp)
{
  echo "Generated by qa-summary.sh; don't edit. \"review\" = the UX engineer checks the diff."
  echo "| Screen | Width | Different | Threshold | Result | Diff |"
  echo "| --- | --- | --- | --- | --- | --- |"
  printf '%s' "$visual${visual:+$'\n'}"
  echo
} > "$body"
replace_section "$report" "Visual comparison" "$body"
{
  echo "Generated by qa-summary.sh from qa/a11y/*.json and qa/a11y-checklist.tsv; don't edit."
  echo "| Screen | Width | Critical | Serious | Moderate | Minor | Report | Method |"
  echo "| --- | --- | --- | --- | --- | --- | --- | --- |"
  printf '%s' "$a11y"
  echo
} > "$body"
replace_section "$report" "Accessibility" "$body"
rm -f "$body"
echo "qa-summary: $(grep -c . <<<"$visual") visual row(s), $(grep -c . <<<"$a11y") accessibility row(s) written to $(phase_rel 2>/dev/null || echo "$dir")/qa-report.md"
